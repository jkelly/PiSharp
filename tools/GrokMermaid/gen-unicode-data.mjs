// Generates MermaidUnicodeData.g.cs: the tables the C# port of grok-mermaid needs to reproduce, under
// the Node runtime executing this script, exactly what the original computes with
//   - width-data.ts WIDTHS (copied verbatim from the library),
//   - /[\p{Alphabetic}\p{N}]/u (labels.ts isAlphanumeric),
//   - Intl.Segmenter('en', { granularity: 'grapheme' }) (width.ts clusters): every code point's
//     Grapheme_Cluster_Break and Indic_Conjunct_Break class, recovered by probing the segmenter itself,
//     so the C# UAX #29 state machine follows this runtime's ICU rather than .NET's StringInfo.
//
// Usage: node gen-unicode-data.mjs <path to grok-mermaid package root> <output .cs path>
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const [libRoot, outPath] = process.argv.slice(2)
if (!libRoot || !outPath) {
  console.error('usage: node gen-unicode-data.mjs <grok-mermaid root> <out.cs>')
  process.exit(2)
}
const pkg = JSON.parse(readFileSync(join(libRoot, 'package.json'), 'utf8'))
const { WIDTHS } = await import(pathToFileURL(join(libRoot, 'dist', 'width-data.js')).href)

const seg = new Intl.Segmenter('en', { granularity: 'grapheme' })
const S = (cp) => String.fromCodePoint(cp)
/** True when the segmenter does not break at UTF-16 offset `at` of `s`. */
const joined = (s, at) => {
  for (const { index } of seg.segment(s)) if (index === at) return false
  return true
}

// GCB codes (low nibble) and InCB codes (high nibble); keep in sync with MermaidGraphemes.cs.
const G = { Other: 0, CR: 1, LF: 2, Control: 3, Extend: 4, ZWJ: 5, RI: 6, Prepend: 7, SpacingMark: 8, L: 9, V: 10, T: 11, LV: 12, LVT: 13, ExtPict: 14 }
const I = { None: 0, Consonant: 1, Extend: 2, Linker: 3 }
const EXT_PICT = /^\p{Extended_Pictographic}$/u
const ALNUM = /^[\p{Alphabetic}\p{N}]$/u
const [A, HL, HV, HT, HLV, K, VIR, ZWJ, EMO, COMB] = ['a', '\u1100', '\u1161', '\u11a8', '\uac00', '\u0915', '\u094d', '\u200d', '\u{1f600}', '\u0300']

function gcb(cp) {
  if (cp === 0x0d) return G.CR
  if (cp === 0x0a) return G.LF
  if (cp === 0x200d) return G.ZWJ
  if (cp >= 0x1f1e6 && cp <= 0x1f1ff) return G.RI
  const c = S(cp)
  const n = c.length
  if (!joined(c + COMB, n)) return G.Control
  if (joined(A + c, 1)) {
    // Extend continues an emoji ZWJ sequence (GB11); SpacingMark does not.
    return joined(EMO + c + ZWJ + EMO, 2 + n + 1) ? G.Extend : G.SpacingMark
  }
  if (joined(c + A, n)) return G.Prepend
  const nbV = joined(c + HV, n)
  const nbT = joined(c + HT, n)
  if (nbV && !nbT) return G.L
  if (nbV && nbT) return joined(HLV + c, 1) ? G.V : G.LV
  if (!nbV && nbT) return joined(HT + c, 1) ? G.T : G.LVT
  return EXT_PICT.test(c) ? G.ExtPict : G.Other
}

function incb(cp, g) {
  const c = S(cp)
  if (g === G.Other || g === G.ExtPict) return joined(K + VIR + c, 2) ? I.Consonant : I.None
  if (g === G.Extend || g === G.ZWJ) {
    if (joined(K + c + K, 1 + c.length)) return I.Linker
    if (joined(K + VIR + c + K, 2 + c.length)) return I.Extend
  }
  return I.None
}

const runs = (pred) => {
  const out = []
  let lo = -1
  for (let cp = 0; cp <= 0x110000; cp++) {
    const hit = cp <= 0x10ffff && pred(cp)
    if (hit && lo === -1) lo = cp
    if (!hit && lo !== -1) {
      out.push([lo, cp - 1])
      lo = -1
    }
  }
  return out
}

const alnum = runs((cp) => !(cp >= 0xd800 && cp <= 0xdfff) && ALNUM.test(S(cp)))

const classes = []
{
  let lo = 0
  let prev = -1
  for (let cp = 0; cp <= 0x110000; cp++) {
    let v
    if (cp > 0x10ffff) v = -2
    else if (cp >= 0xd800 && cp <= 0xdfff) v = G.Other // a lone surrogate segments like Other
    else {
      const g = gcb(cp)
      v = g | (incb(cp, g) << 4)
    }
    if (v !== prev) {
      if (prev !== -1 && prev !== 0) classes.push([lo, cp - 1, prev])
      lo = cp
      prev = v
    }
  }
}

const hex = (n) => `0x${n.toString(16)}`
const rows = (items, per) => {
  const lines = []
  for (let i = 0; i < items.length; i += per) lines.push(`        ${items.slice(i, i + per).join(', ')},`)
  return lines.join('\n')
}

const cs = `// grok-mermaid ${pkg.version} (Apache-2.0): src/width-data.ts, plus Unicode tables for src/labels.ts and src/width.ts — used by Pi abe508e1b89912adde45528136c3221eb69acdd7 (MIT): packages/coding-agent/src/modes/interactive/components/mermaid.ts.
// <auto-generated> by gen-unicode-data.mjs under Node ${process.version} (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}). Do not edit.
// Widths come from the library's own table (the unicode-width crate). Alphanumeric mirrors /[\\p{Alphabetic}\\p{N}]/u and the
// grapheme classes mirror Intl.Segmenter on that runtime. Unicode data: copyright Unicode, Inc. (Unicode License v3).
namespace PiSharp.Cli.Interactive.Mode.Mermaid;

internal static class MermaidUnicodeData
{
    internal const string Profile = "node${process.versions.node}-icu${process.versions.icu}-unicode${process.versions.unicode}";

    /// <summary>width-data.ts WIDTHS: sorted, contiguous [lo, hi, width] runs over the whole code point space.</summary>
    internal static readonly int[] Widths =
    [
${rows(WIDTHS.map(([lo, hi, w]) => `${hex(lo)}, ${hex(hi)}, ${w}`), 4)}
    ];

    /// <summary>Sorted inclusive [lo, hi] runs of \\p{Alphabetic} or \\p{N}.</summary>
    internal static readonly int[] Alphanumeric =
    [
${rows(alnum.map(([lo, hi]) => `${hex(lo)}, ${hex(hi)}`), 6)}
    ];

    /// <summary>Sorted inclusive [lo, hi, class] runs; class = GCB | InCB &lt;&lt; 4. Missing code points are Other/None.</summary>
    internal static readonly int[] Graphemes =
    [
${rows(classes.map(([lo, hi, v]) => `${hex(lo)}, ${hex(hi)}, ${v}`), 4)}
    ];
}
`
writeFileSync(outPath, cs)
console.log(`widths ${WIDTHS.length}, alnum ${alnum.length}, grapheme runs ${classes.length}`)
